function readLocale(): Locale {
  if (typeof window === 'undefined') return 'zh-CN';
  try { return window.localStorage.getItem(STORAGE_KEY) === 'en-US' ? 'en-US' : 'zh-CN'; }
  catch { return 'zh-CN'; }
}

let activeLocale: Locale = readLocale();
const listeners = new Set<() => void>();

function syncAppLocale(locale: Locale): void {
  if (typeof window === 'undefined') return;
  const bridge = (window as Window & { piDesktop?: { setAppLocale?(value: Locale): Promise<void> } }).piDesktop;
  const request = bridge?.setAppLocale?.(locale);
  if (request) void request.catch(() => {});
}

function notify(): void {
  for (const listener of listeners) listener();
}

export function getLocale(): Locale { return activeLocale; }

export function translate(key: string, params?: TranslationParams, locale: Locale = activeLocale): string {
  const template = translations[key]?.[locale] ?? translations[key]?.['zh-CN'] ?? key;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (_match: string, name: string) => String(params?.[name] ?? `{${name}}`));
}

export function setLocale(next: Locale): void {
  if (activeLocale === next) return;
  activeLocale = next;
  if (typeof window !== 'undefined') {
    try { window.localStorage.setItem(STORAGE_KEY, next); } catch { /* storage may be unavailable */ }
    document.documentElement.lang = next;
    syncAppLocale(next);
  }
  notify();
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

if (typeof window !== 'undefined') {
  document.documentElement.lang = activeLocale;
  syncAppLocale(activeLocale);
  window.addEventListener('storage', (event) => {
    if (event.key !== STORAGE_KEY) return;
    const next = readLocale();
    if (next !== activeLocale) { activeLocale = next; document.documentElement.lang = next; syncAppLocale(next); notify(); }
  });
}

export function useT(): { t: Translate; locale: Locale; setLocale: typeof setLocale } {
  const locale = useSyncExternalStore<Locale>(subscribe, getLocale, () => 'zh-CN');
  const t: Translate = (key, params) => translate(key, params, locale);
  return { t, locale, setLocale };
}
